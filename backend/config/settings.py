_HOSTNAME_LABEL_REGEX = re.compile(r"^(?!-)[a-zA-Z0-9-]{1,63}(?<!-)$")


def _is_valid_hostname(host: str) -> bool:
    """Check if host is a valid domain name, localhost, IPv4, or IPv6."""
    if not host or len(host) > 253:
        return False
    if "*" in host:
        return False

    # Check for IPv6 (bracketed [::1] or unbracketed ::1)
    ipv6_cand = host[1:-1] if host.startswith("[") and host.endswith("]") else host
    try:
        ipaddress.IPv6Address(ipv6_cand)
        return True
    except ValueError:
        pass

    # Check for IPv4
    try:
        ipaddress.IPv4Address(host)
        return True
    except ValueError:
        pass

    # Check domain name labels (e.g. 'localhost', 'zenflowbd.vercel.app')
    labels = host.split(".")
    return all(_HOSTNAME_LABEL_REGEX.match(label) for label in labels)


def _normalize_origin(origin: str) -> str | None:
    """
    Validate and normalize an HTTP or HTTPS origin per RFC 6454.
    An origin consists strictly of scheme://host[:port].

    Requirements enforced:
    - Accepts only 'http' and 'https' schemes.
    - Supports valid hostnames, IPv4, IPv6, and valid port numbers (1-65535).
    - Rejects credentials/userinfo (@).
    - Rejects wildcard origins (*).
    - Rejects paths other than an optional root '/'.
    - Rejects query strings and fragments.
    - Rejects malformed ports and malformed hostnames.
    - Strips surrounding whitespace and matching quotes.
    - Normalizes scheme and hostname to lowercase.
    - Strips default ports 80 for HTTP and 443 for HTTPS.
    - Preserves non-default ports.
    - A missing scheme may only be interpreted as HTTPS if the input is
      otherwise strictly a valid bare hostname with an optional port.
    - Returns None for any invalid or malformed input.
    """
    if not origin or not isinstance(origin, str):
        return None

    cleaned = origin.strip().strip("'\"")
    if not cleaned:
        return None

    if "://" in cleaned:
        raw_scheme, rest = cleaned.split("://", 1)
        scheme = raw_scheme.lower()
        if scheme not in ("http", "https"):
            return None
        target = f"{scheme}://{rest}"
    else:
        # No '://' present.
        # A missing scheme may only be interpreted as HTTPS if the input is
        # strictly a valid bare hostname with an optional valid port.
        if any(c in cleaned for c in ("/", "?", "#", "@", ",", "(", ")")):
            return None
        if ":" in cleaned:
            if cleaned.startswith("[") and "]:" in cleaned:
                host_part, port_part = cleaned.split("]:", 1)
                host_part = host_part + "]"
            elif not cleaned.startswith("["):
                host_part, port_part = cleaned.rsplit(":", 1)
            else:
                return None
            if not port_part.isdigit() or not (1 <= int(port_part) <= 65535):
                return None
            if not _is_valid_hostname(host_part):
                return None
        else:
            if not _is_valid_hostname(cleaned):
                return None
        target = f"https://{cleaned}"

    try:
        parsed = urlsplit(target)
    except Exception:
        return None

    scheme = parsed.scheme.lower()
    if scheme not in ("http", "https"):
        return None

    # Reject user credentials in origin
    if parsed.username or parsed.password or "@" in parsed.netloc:
        return None

    # Reject paths other than an optional root '/'
    if parsed.path and parsed.path != "/":
        return None

    # Reject query strings and fragments
    if parsed.query or parsed.fragment:
        return None

    # Validate port
    try:
        port = parsed.port
    except ValueError:
        return None

    # Validate hostname
    hostname = parsed.hostname
    if not hostname or not _is_valid_hostname(hostname):
        return None

    # Format IPv6 with brackets
    try:
        ipaddress.IPv6Address(hostname)
        host_str = f"[{hostname.lower()}]"
    except ValueError:
        host_str = hostname.lower()

    # Normalize default ports
    if port:
        if (scheme == "http" and port == 80) or (scheme == "https" and port == 443):
            return f"{scheme}://{host_str}"
        return f"{scheme}://{host_str}:{port}"

    return f"{scheme}://{host_str}"


