def _parse_origins(
    raw: str | list[str] | tuple[str, ...],
    extra_defaults: list[str] | None = None,
) -> list[str]:
    """
    Parse comma-separated origins from environment variables or string lists,
    normalizing each origin, discarding invalid entries, avoiding duplicates,
    and preserving localhost development origins.
    """
    origins: list[str] = []
    items = raw.split(",") if isinstance(raw, str) else list(raw)

    for item in items:
        cleaned = _normalize_origin(item)
        if cleaned and cleaned not in origins:
            origins.append(cleaned)

    # Always preserve localhost development origins
    for dev_origin in DEV_DEFAULT_ORIGINS:
        cleaned_dev = _normalize_origin(dev_origin)
        if cleaned_dev and cleaned_dev not in origins:
            origins.append(cleaned_dev)

    if extra_defaults:
        for extra in extra_defaults:
            cleaned_extra = _normalize_origin(extra)
            if cleaned_extra and cleaned_extra not in origins:
                origins.append(cleaned_extra)

    return origins


